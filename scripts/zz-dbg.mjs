import { _electron as electron } from 'playwright-core';
import path from 'node:path'; import fs from 'node:fs'; import os from 'node:os';
const ROOT = '/home/user/marginalia';
const home = fs.mkdtempSync(path.join(os.tmpdir(), 'mg-dbg-'));
const UD = path.join(home,'d');
let app, page;
async function launch() {
app = await electron.launch({ executablePath: path.join(ROOT, 'node_modules/electron/dist/electron'), args: ['--no-sandbox', ROOT], env: { ...process.env, HOME: home, MARGINALIA_E2E: '1', MARGINALIA_E2E_USER_DATA: UD, VITE_DEV_SERVER_URL: '', MG_DBG: '1' } });
app.process().stderr.on('data', (d) => { if (/secrets|espaces|Error occ/i.test(d)) process.stdout.write('[err] ' + d); });
page = await app.firstWindow();
await page.waitForFunction(() => window.__store && window.__store.getState().ready);
}
await launch();
const id = await page.evaluate(() => window.__store.getState().createWorkspace('Privé').id);
await page.evaluate(() => window.__store.getState().updateSettings({ tourDone: true, mascot: 'off' }));
await new Promise(r=>setTimeout(r,1000));
await page.click(`[data-ws-id="${id}"]`, { button: 'right' });
await page.getByRole('menuitem', { name: 'Chiffrer cet espace…' }).click();
await page.fill('[data-testid="space-new-password"]', 'abcdefghij');
await page.fill('[data-testid="space-new-password2"]', 'abcdefghij');
await page.click('[data-testid="space-encrypt-go"]');
await page.waitForSelector('[data-testid="space-recovery"]');
await page.check('[data-testid="space-kept"]'); await page.click('[data-testid="space-encrypt-go"]');
await page.waitForSelector('[data-testid="space-encrypt-dialog"]', { state: 'detached', timeout: 30000 });
await new Promise(r=>setTimeout(r,1500));
await app.close();
await launch();
await page.reload();
await page.waitForFunction(() => window.__store && window.__store.getState().ready);
console.log(await page.evaluate((id) => window.marginalia.spaces.unlock(id, 'abcdefghij').then(r => JSON.stringify(r).slice(0,100), e => 'ERR ' + e.message), id));
await app.close();
