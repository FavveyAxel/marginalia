console.log('direct', await page.evaluate(() => Promise.race([window.marginalia.security.unlockPassword('abcdefghij').then(r => JSON.stringify(r), e => 'ERR '+e.message), new Promise(r => setTimeout(() => r('TIMEOUT'), 15000))])));
await page.click('#lock-password'); await page.keyboard.type('abcdefghij', { delay: 15 });
console.log('len', await page.inputValue('#lock-password'));
await page.keyboard.press('Enter');
await new Promise(r=>setTimeout(r,4000));
